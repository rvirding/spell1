-module(spell1_testing).

-export([setup/0,
         teardown/0]).
-export([generate_erl_files/0,
         generate_lfe_files/0]).

-include_lib("eunit/include/eunit.hrl").

%%%=============================================================================
%%% Public
%%%=============================================================================

setup() ->
    fun() ->
            setup_apps()
    end.

teardown() ->
    fun(Apps) ->
            [teardown_app(App) || App <- Apps]
    end.

%%%=============================================================================
%%% Internal functions
%%%=============================================================================

%%------------------------------------------------------------------------------
%% @private
%%------------------------------------------------------------------------------

%%------------------------------------------------------------------------------
%% @private
%%------------------------------------------------------------------------------
setup_apps() ->
    application:load(sasl),
    ok = application:set_env(sasl, sasl_error_logger, false),
    {ok, Apps} = application:ensure_all_started(spell1),
    Apps.

%%------------------------------------------------------------------------------
%% @private
%%------------------------------------------------------------------------------
teardown_app(App) ->
    error_logger:tty(false),
    application:stop(App),
    error_logger:tty(true).

